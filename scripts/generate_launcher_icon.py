"""Generates PageDrop's launcher icon: Big Brother's halftone eye with a red redaction bar.

Usage: python3 scripts/generate_launcher_icon.py app/src/main/res [preview.svg]
"""
import math, sys
res = sys.argv[1]; preview = sys.argv[2] if len(sys.argv) > 2 else None
INK, PAPER, RED = "#141414", "#EDE9DE", "#B3261E"
S = 2/3                      # launchers show roughly the middle 72dp of 108dp
cx = cy = 54
half_w, half_h = 35.0, 17.5  # almond eye
c = (half_w**2 - half_h**2) / (2*half_h); R = c + half_h
def in_eye(x, y):
    return math.hypot(x-cx, y-(cy+c)) <= R and math.hypot(x-cx, y-(cy-c)) <= R
step, rmax, rmin, fade = 3.5, 1.85, 0.5, 38.0
dots = []
y = cy - half_h - step
row = 0
while y <= cy + half_h + step:
    x = 4 + (row % 2) * step/2
    while x <= 104:
        if in_eye(x, y):
            t = max(0.0, min(1.0, 1 - math.hypot(x-cx, y-cy)/fade))
            r = rmin + (rmax-rmin)*t
            dots.append((x, y, r))
        x += step
    y += step; row += 1
def circ(x, y, r):
    return f"M{x-r:.2f},{y:.2f}a{r:.2f},{r:.2f} 0 1,0 {2*r:.2f},0a{r:.2f},{r:.2f} 0 1,0 {-2*r:.2f},0Z"
dot_path = "".join(circ(*d) for d in dots)
iris = circ(cx, cy, 12.5)
# redaction bar: full-bleed, rotated -8 degrees about the centre
a = math.radians(-8); bh = 8.5
pts = [(-10, cy-bh/2), (118, cy-bh/2), (118, cy+bh/2), (-10, cy+bh/2)]
rot = [(cx+(px-cx)*math.cos(a)-(py-cy)*math.sin(a), cy+(px-cx)*math.sin(a)+(py-cy)*math.cos(a)) for px, py in pts]
bar = "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in rot) + "Z"
def vector(color, comment, bar_color=None):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{color}" android:pathData="{dot_path}" />
    <path android:fillColor="{color}" android:pathData="{iris}" />
    <path android:fillColor="{bar_color or color}" android:pathData="{bar}" />
</vector>
'''
open(f"{res}/drawable/ic_launcher_foreground.xml","w").write(vector(INK, "Redacted eye: Big Brother's halftone eye with a redaction bar across it. Generated by scripts/generate_launcher_icon.py.", RED))
open(f"{res}/drawable/ic_launcher_monochrome.xml","w").write(vector("#FFFFFFFF", "Single-colour redacted eye for Android themed icons."))
open(f"{res}/drawable/ic_launcher_background.xml","w").write(f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Newsprint paper, matching the halftone print look of the library background. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{PAPER}" />
</shape>
''')
if preview: open(preview,"w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="360" height="360"><rect x="0" y="0" width="108" height="108" fill="{PAPER}"/><path fill="{INK}" d="{dot_path}"/><path fill="{INK}" d="{iris}"/><path fill="{RED}" d="{bar}"/></svg>')
print(len(dots), "dots;", len(dot_path), "chars")
